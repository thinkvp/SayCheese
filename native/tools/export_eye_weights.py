"""Writes native/src/eye_model_weights.h from open_closed_eye.onnx.

The eye classifier (Intel Open Model Zoo open-closed-eye-0001, Apache-2.0) is
small enough to run as plain C++ loops, so its weights are compiled in rather
than shipping an inference runtime. Run once when the model changes (from the repo root):
    engine/.venv/Scripts/python -I native/tools/export_eye_weights.py engine/models/open_closed_eye.onnx
Needs `pip install onnx` (build time only).
"""
import os
import sys

import onnx
from onnx import numpy_helper

model = onnx.load(sys.argv[1])
weights = {t.name: numpy_helper.to_array(t) for t in model.graph.initializer}
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "eye_model_weights.h")

lines = [
    "// Generated by native/tools/export_eye_weights.py -- do not edit.",
    "// Weights of Intel Open Model Zoo open-closed-eye-0001 (Apache-2.0).",
    "#pragma once",
    "",
]
for name in ("conv1.weight", "conv1.bias", "conv2.weight", "conv2.bias",
             "conv3.weight", "conv3.bias", "conv4.weight"):
    arr = weights[name].astype("float32").reshape(-1)
    ident = name.replace(".", "_")
    shape = "x".join(str(d) for d in weights[name].shape)
    lines.append(f"// {name} {shape}")
    lines.append(f"static const float k_{ident}[{arr.size}] = {{")
    for i in range(0, arr.size, 8):
        lines.append("    " + ", ".join(f"{v:.9g}f" for v in arr[i:i + 8]) + ",")
    lines.append("};")
    lines.append("")
with open(out, "w", newline="\n") as fh:
    fh.write("\n".join(lines))
print("wrote", os.path.normpath(out))
